/* Reads English from the page, then swaps every tagged string on demand. */
export function createI18n(root = document) {
  const textNodes = [...root.querySelectorAll('[data-i18n]')];
  const attrNodes = [...root.querySelectorAll('[data-i18n-attr]')].map((el) => ({
    el,
    pairs: el.dataset.i18nAttr.split(',').map((p) => p.trim().split(':')),
  }));
  const en = { ...EN_JS };
  textNodes.forEach((el) => { if (!(el.dataset.i18n in en)) en[el.dataset.i18n] = el.innerHTML.trim(); });
  attrNodes.forEach(({ el, pairs }) => pairs.forEach(([attr, key]) => { if (!(key in en)) en[key] = el.getAttribute(attr) || ''; }));

  let lang = 'en';
  const t = (key, vars) => {
    let s = (DICT[lang] && DICT[lang][key]) ?? en[key] ?? key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? vars[k] : ''));
    return s;
  };
  const plain = (html) => { const d = document.createElement('textarea'); d.innerHTML = html; return d.value; };

  function apply(next) {
    lang = LANGS.includes(next) ? next : 'en';
    textNodes.forEach((el) => { const v = t(el.dataset.i18n); if (el.innerHTML.trim() !== v) el.innerHTML = v; });
    attrNodes.forEach(({ el, pairs }) => pairs.forEach(([attr, key]) => el.setAttribute(attr, plain(t(key)))));
    document.documentElement.lang = lang;
    document.documentElement.dir = RTL.has(lang) ? 'rtl' : 'ltr';
    return lang;
  }

  return { t, apply, get lang() { return lang; } };
}
